def leaves(value):
 if isinstance(value,str):yield value
 elif isinstance(value,list):
  for v in value:yield from leaves(v)
 elif isinstance(value,dict):
  for v in value.values():yield from leaves(v)

def replace(value,words):
 if isinstance(value,str):return next(words)
 if isinstance(value,list):return [replace(v,words) for v in value]
 if isinstance(value,dict):return {k:replace(v,words) for k,v in value.items()}
 return value

